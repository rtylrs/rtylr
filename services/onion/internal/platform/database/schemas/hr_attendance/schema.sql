CREATE TABLE IF NOT EXISTS `hr_attendance_records` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `employee_id` bigint NOT NULL,
  `location_id` bigint NOT NULL DEFAULT '0',
  `date` date NOT NULL,
  `clock_in_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `clock_out_at` timestamp NULL DEFAULT NULL,
  `duration_minutes` int DEFAULT NULL,
  `clock_in_method` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'app',
  `clock_in_lat` double DEFAULT NULL,
  `clock_in_lng` double DEFAULT NULL,
  `is_late` tinyint(1) NOT NULL DEFAULT '0',
  `late_minutes` int NOT NULL DEFAULT '0',
  `status` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'present',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_attendance_owner` (`owner_id`),
  KEY `idx_attendance_employee` (`owner_id`,`employee_id`),
  KEY `idx_attendance_date` (`owner_id`,`date`),
  KEY `idx_attendance_location_date` (`owner_id`,`location_id`,`date`),
  KEY `idx_attendance_active` (`owner_id`,`employee_id`,`clock_out_at`),
  KEY `idx_hr_attendance_business_employee_date` (`business_id`,`employee_id`,`date`),
  KEY `idx_hr_attendance_business_location_date` (`business_id`,`location_id`,`date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `hr_attendance_config` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `app_enabled` tinyint(1) NOT NULL DEFAULT '1',
  `qr_enabled` tinyint(1) NOT NULL DEFAULT '0',
  `gps_enabled` tinyint(1) NOT NULL DEFAULT '0',
  `pin_enabled` tinyint(1) NOT NULL DEFAULT '0',
  `facial_enabled` tinyint(1) NOT NULL DEFAULT '0',
  `geofence_radius_m` int NOT NULL DEFAULT '200',
  `default_location_lat` double NOT NULL DEFAULT '0',
  `default_location_lng` double NOT NULL DEFAULT '0',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_attendance_config_owner` (`owner_id`),
  KEY `idx_hr_attendance_config_business` (`business_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
