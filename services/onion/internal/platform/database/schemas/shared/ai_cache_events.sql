CREATE TABLE IF NOT EXISTS `ai_cache_events` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `event_id` varchar(96) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `occurred_at` datetime(3) NOT NULL,
  `outcome` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `mode` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `provider` varchar(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `reason` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `cache_key_preview` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `business_id` bigint DEFAULT NULL,
  `user_id` bigint DEFAULT NULL,
  `prompt_chars` int DEFAULT NULL,
  `response_chars` int DEFAULT NULL,
  `provider_tokens` int DEFAULT NULL,
  `estimated_savings_tokens` int DEFAULT NULL,
  `latency_ms` bigint DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_ai_cache_events_event_id` (`event_id`),
  KEY `idx_ai_cache_events_occurred_at` (`occurred_at`),
  KEY `idx_ai_cache_events_business_id` (`business_id`),
  KEY `idx_ai_cache_events_outcome` (`outcome`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
