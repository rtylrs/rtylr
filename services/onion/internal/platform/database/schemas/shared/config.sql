CREATE TABLE IF NOT EXISTS config (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_id INT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    site_name TEXT NULL,
    logo_url TEXT NULL,
    favicon_url TEXT NULL,
    meta_tags JSON NULL DEFAULT (JSON_ARRAY()),
    contact_email TEXT NOT NULL,
    contact_number TEXT NOT NULL,
    instagram TEXT NULL,
    maintenance_mode BOOLEAN DEFAULT FALSE,
    maintenance_notice TEXT NULL,
    addons_enabled BOOLEAN DEFAULT FALSE,
    enable_reviews BOOLEAN DEFAULT FALSE,
    enable_wishlist BOOLEAN DEFAULT FALSE,
    enable_newsletter_signup BOOLEAN DEFAULT FALSE,
    about_content TEXT NOT NULL,
    footer_sub_text TEXT NULL,
    business_slug VARCHAR(255) NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT NULL
);
