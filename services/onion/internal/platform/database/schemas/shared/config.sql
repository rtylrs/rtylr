CREATE TABLE IF NOT EXISTS config (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_id INT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    site_name TEXT NULL,
    logo_url TEXT NULL,
    favicon_url TEXT NULL,
    meta_tags JSON NULL DEFAULT (JSON_ARRAY()),
    contact_email TEXT NOT NULL,
    contact_number TEXT NOT NULL,
    sender_email TEXT NULL,
    email_provider VARCHAR(32) NOT NULL DEFAULT 'resend',
    sender_name VARCHAR(255) NULL,
    reply_to_email TEXT NULL,
    email_notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    smtp_host VARCHAR(255) NULL,
    smtp_port INT NULL,
    smtp_username VARCHAR(255) NULL,
    smtp_password_hash TEXT NULL,
    website TEXT NULL,
    maps_url TEXT NULL,
    address TEXT NULL,
    city TEXT NULL,
    zipcode TEXT NULL,
    country TEXT NULL,
    instagram TEXT NULL,
    maintenance_mode BOOLEAN DEFAULT FALSE,
    maintenance_notice TEXT NULL,
    addons_enabled BOOLEAN DEFAULT FALSE,
    enable_reviews BOOLEAN DEFAULT FALSE,
    enable_wishlist BOOLEAN DEFAULT FALSE,
    enable_newsletter_signup BOOLEAN DEFAULT FALSE,
    about_content TEXT NOT NULL,
    footer_sub_text TEXT NULL,
    business_slug VARCHAR(255) NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT NULL,
    INDEX idx_config_business (business_id),
    INDEX idx_config_owner (owner_id)
);
