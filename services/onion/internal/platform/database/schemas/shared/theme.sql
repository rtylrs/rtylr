    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_id INT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    primary_color TEXT NULL,
    secondary_color TEXT NULL,
    accent_color TEXT NULL,
    dark_green_color TEXT NULL,
    background_color TEXT NULL,
    bg_color TEXT NULL,
    surface_color TEXT NULL,
    light_color TEXT NULL,
    dark_color TEXT NULL,
    item_background_color TEXT NULL,
    error_color TEXT NULL,
    success_color TEXT NULL,
    warning_color TEXT NULL,
    info_color TEXT NULL,
    text_primary_color TEXT NULL,
    text_secondary_color TEXT NULL,
    subtext_color TEXT NULL,
    light_gray_color TEXT NULL,
    active_color TEXT NULL,
    admin_background_color TEXT NULL,
    admin_primary_color TEXT NULL,
    vendor_background_color TEXT NULL,
    border_color TEXT NULL,
    font_family_primary TEXT NULL,
    font_family_secondary TEXT NULL,
    font_size_base TEXT NULL,
    font_size_heading TEXT NULL,
    mobile_breakpoint TEXT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
