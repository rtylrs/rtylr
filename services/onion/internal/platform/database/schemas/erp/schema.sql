  PRIMARY KEY (`id`),
  KEY `idx_erp_products_business_brand` (`business_id`,`brand_id`),
  KEY `idx_erp_products_business_sku` (`business_id`,`sku`),
  KEY `idx_erp_products_business_barcode` (`business_id`,`barcode`),
  KEY `idx_erp_products_business_inventory_name` (`business_id`,`is_active`,`track_inventory`,`name`),
  KEY `idx_erp_products_business_inventory_stock` (`business_id`,`is_active`,`track_inventory`,`stock_quantity`),
  KEY `idx_erp_products_business_name` (`business_id`,`name`),
  KEY `idx_erp_products_business_category_name` (`business_id`,`category_id`,`name`),
  KEY `idx_erp_products_business_active` (`business_id`,`is_active`,`track_inventory`),
  FULLTEXT KEY `idx_erp_products_search` (`name`,`sku`,`barcode`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `erp_inventory_transactions` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `product_id` bigint NOT NULL,
  `type` enum('purchase','sale','adjustment','return','waste') COLLATE utf8mb4_unicode_ci NOT NULL,
  `quantity_change` decimal(10,3) NOT NULL,
  `quantity_before` decimal(10,3) NOT NULL,
  `quantity_after` decimal(10,3) NOT NULL,
  `reference_id` bigint DEFAULT NULL,
  `reference_type` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `notes` text COLLATE utf8mb4_unicode_ci,
  `created_by` bigint DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_erp_inventory_tx_business_product_created` (`business_id`,`product_id`,`created_at`),
  KEY `idx_erp_inventory_tx_business_reference` (`business_id`,`reference_type`,`reference_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `erp_purchase_orders` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `supplier_id` bigint NOT NULL,
  `po_number` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  `status` enum('draft','sent','approved','partial','received','cancelled') COLLATE utf8mb4_unicode_ci DEFAULT 'draft',
  `subtotal` decimal(10,2) DEFAULT '0.00',
  `tax_amount` decimal(10,2) DEFAULT '0.00',
  `total` decimal(10,2) DEFAULT '0.00',
  `expected_delivery` date DEFAULT NULL,
  `received_at` timestamp NULL DEFAULT NULL,
  `notes` text COLLATE utf8mb4_unicode_ci,
  `created_by` bigint DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `destination_location_id` bigint DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_erp_purchase_orders_business_created` (`business_id`,`created_at`),
  KEY `idx_erp_purchase_orders_business_status_created` (`business_id`,`status`,`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

