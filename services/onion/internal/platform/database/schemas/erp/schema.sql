  `width` decimal(10,2) NOT NULL DEFAULT '0.00',
  `height` decimal(10,2) NOT NULL DEFAULT '0.00',
  `dimension_unit` varchar(8) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'cm',
  `country_of_origin` varchar(2) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
