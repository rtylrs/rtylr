  KEY `idx_crm_customers_business_tier` (`business_id`,`loyalty_tier`),
  KEY `idx_crm_customers_owner` (`owner_id`),
  KEY `idx_crm_customers_owner_active` (`owner_id`,`is_active`),
  KEY `idx_crm_customers_owner_created` (`owner_id`,`created_at`),
  FULLTEXT KEY `idx_crm_customers_search` (`first_name`,`last_name`,`email`,`phone`)
