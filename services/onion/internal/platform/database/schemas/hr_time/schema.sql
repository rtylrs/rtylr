CREATE TABLE IF NOT EXISTS `hr_time_entries` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `employee_id` bigint NOT NULL,
  `timesheet_id` bigint DEFAULT NULL,
  `project_id` bigint DEFAULT NULL,
  `task_id` bigint DEFAULT NULL,
  `category_id` bigint DEFAULT NULL,
  `date` date NOT NULL,
  `duration_minutes` int NOT NULL,
  `start_time` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `end_time` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `description` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `is_billable` tinyint(1) NOT NULL DEFAULT '0',
  `status` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'draft',
  `rejection_reason` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `approved_by` bigint DEFAULT NULL,
  `source` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'manual',
  `billable_invoice_id` bigint DEFAULT NULL,
  `export_batch_id` bigint DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `work_day_id` bigint DEFAULT NULL,
  `work_type_id` bigint DEFAULT NULL,
  `work_mode` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `timezone` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `client_key` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `logged_by` bigint DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_time_entries_client_key_tenant` (`owner_id`,`business_id`,`client_key`),
  KEY `idx_time_entries_owner` (`owner_id`),
  KEY `idx_time_entries_employee` (`owner_id`,`employee_id`),
  KEY `idx_time_entries_date` (`owner_id`,`date`),
  KEY `idx_time_entries_timesheet` (`owner_id`,`timesheet_id`),
  KEY `idx_hr_time_entries_business_employee_date` (`business_id`,`employee_id`,`date`),
  KEY `idx_hr_time_entries_business_status_billable_date` (`business_id`,`status`,`is_billable`,`date`),
  KEY `idx_hr_time_entries_business_project_date` (`business_id`,`project_id`,`date`),
  KEY `idx_time_entries_work_day` (`owner_id`,`work_day_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `hr_timesheets` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `employee_id` bigint NOT NULL,
  `period_start` date NOT NULL,
  `period_end` date NOT NULL,
  `status` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'draft',
  `current_approval_level` int NOT NULL DEFAULT '0',
  `submitted_at` timestamp NULL DEFAULT NULL,
  `total_minutes` int NOT NULL DEFAULT '0',
  `rejection_reason` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_timesheet_period` (`owner_id`,`employee_id`,`period_start`),
  KEY `idx_timesheets_owner` (`owner_id`),
  KEY `idx_timesheets_employee` (`owner_id`,`employee_id`),
  KEY `idx_timesheets_status` (`owner_id`,`status`),
  KEY `idx_hr_timesheets_business_employee_period` (`business_id`,`employee_id`,`period_start`),
  KEY `idx_hr_timesheets_business_status_period` (`business_id`,`status`,`period_start`,`period_end`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `hr_timesheet_approval_actions` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `timesheet_id` bigint NOT NULL,
  `approver_id` bigint NOT NULL,
  `action` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `level` int NOT NULL,
  `comment` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_approval_actions_timesheet` (`owner_id`,`timesheet_id`),
  KEY `idx_hr_approval_actions_business_timesheet_created` (`business_id`,`timesheet_id`,`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
