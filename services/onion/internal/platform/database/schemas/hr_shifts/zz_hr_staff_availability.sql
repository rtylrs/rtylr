CREATE TABLE IF NOT EXISTS `hr_staff_availability` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `owner_id` bigint NOT NULL,
  `business_id` bigint NOT NULL DEFAULT '0',
  `staff_id` bigint NOT NULL,
  `day_of_week` tinyint DEFAULT NULL,
  `specific_date` date DEFAULT NULL,
  `start_time` time NOT NULL,
  `end_time` time NOT NULL,
  `is_available` tinyint(1) NOT NULL DEFAULT '1',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `day_key` tinyint GENERATED ALWAYS AS (ifnull(`day_of_week`,-(1))) STORED,
  `date_key` date GENERATED ALWAYS AS (ifnull(`specific_date`,_utf8mb4'1000-01-01')) STORED,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_hr_staff_availability` (`business_id`,`staff_id`,`day_key`,`date_key`,`start_time`),
  KEY `idx_hr_staff_availability_owner` (`owner_id`),
  KEY `idx_hr_staff_availability_staff` (`business_id`,`staff_id`),
  KEY `idx_hr_staff_availability_date` (`business_id`,`specific_date`),
  CONSTRAINT `chk_hr_staff_availability_kind` CHECK (((`day_of_week` is null) <> (`specific_date` is null)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
