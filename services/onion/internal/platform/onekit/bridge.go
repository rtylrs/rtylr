package onekit

import (
	"context"
	"encoding/json"
	stdErrors "errors"
	"fmt"
	"net/http"
	"strings"

	onekithttp "github.com/1homsi/onekit/http"
	"github.com/go-chi/chi/v5"
	"google.golang.org/protobuf/proto"

	platformerrors "github.com/voxire/onion/internal/platform/errors"
	"github.com/voxire/onion/internal/platform/logger"
)

// LegacyHandler adapts the current Onion handler contract to generated oneKit
// service methods while modules move from hand-written request binding to proto
// service contracts.
type LegacyHandler[Req any, Res proto.Message] interface {
	Serve(ctx context.Context, req *Req) (Res, *platformerrors.ServerError)
}

// Serve calls a current Onion handler and returns a regular error for the
// oneKit generated server interface.
func Serve[Req any, Res proto.Message](ctx context.Context, handler LegacyHandler[Req, Res], req *Req) (Res, error) {
	res, serverError := handler.Serve(ctx, req)
	if serverError != nil {
		var zero Res
		return zero, serverError
	}

	return res, nil
}

// NewMux creates the private stdlib mux expected by generated oneKit servers.
func NewMux() *http.ServeMux {
	return http.NewServeMux()
}

// Mount registers generated oneKit HTTP patterns on the chi router. Patterns
// use the same shape generated by oneKit, for example "GET /erp/products".
func Mount(router chi.Router, mux http.Handler, patterns ...string) error {
	for _, pattern := range patterns {
		method, path, ok := strings.Cut(strings.TrimSpace(pattern), " ")
		if !ok || method == "" || path == "" {
			return fmt.Errorf("invalid oneKit route pattern %q", pattern)
		}

		router.Method(method, path, mux)
	}

	return nil
}

// ErrorHandler preserves Onion's public JSON error envelope for generated
// oneKit routes.
func ErrorHandler(w http.ResponseWriter, r *http.Request, err error) proto.Message {
	serverError := serverErrorFromOneKit(err)
	writeServerError(r.Context(), w, serverError)

	return nil
}

func serverErrorFromOneKit(err error) *platformerrors.ServerError {
	if err == nil {
		return &platformerrors.ServerError{
			HTTPCode: http.StatusInternalServerError,
			Code:     http.StatusInternalServerError,
			Message:  "Unknown error",
		}
	}

	var serverError *platformerrors.ServerError
	if stdErrors.As(err, &serverError) {
		return serverError
	}

	var validationError *onekithttp.ValidationError
	if stdErrors.As(err, &validationError) {
		return &platformerrors.ServerError{
			HTTPCode: http.StatusBadRequest,
			Code:     http.StatusBadRequest,
			Message:  validationMessage(validationError),
		}
	}

	var oneKitError *onekithttp.Error
	if stdErrors.As(err, &oneKitError) && oneKitError.GetMessage() != "" {
		return &platformerrors.ServerError{
			HTTPCode: http.StatusInternalServerError,
			Code:     http.StatusInternalServerError,
			Message:  oneKitError.GetMessage(),
		}
	}

	return platformerrors.FromError(err, "Failed to process request")
}

func validationMessage(validationError *onekithttp.ValidationError) string {
	violations := validationError.GetViolations()
	if len(violations) == 0 {
		return "Validation failed"
	}

	first := violations[0]
	field := strings.TrimSpace(first.GetField())
	description := strings.TrimSpace(first.GetDescription())
	switch {
	case field != "" && description != "":
		return field + ": " + description
	case description != "":
		return description
	case field != "":
		return field + " is invalid"
	default:
		return "Validation failed"
	}
}

func writeServerError(ctx context.Context, w http.ResponseWriter, serverError *platformerrors.ServerError) {
	w.Header().Set("Content-Type", "application/json")

	httpCode := serverError.HTTPCode
	if httpCode == 0 {
		if serverError.Code >= 400 && serverError.Code < 600 {
			httpCode = serverError.Code
		} else {
			httpCode = http.StatusInternalServerError
		}
	}

	w.WriteHeader(httpCode)

	response := platformerrors.ErrorResponse{
		Error:  *serverError,
		Status: "error",
	}
	if err := json.NewEncoder(w).Encode(response); err != nil {
		logger.Ctx(ctx).Error("Failed to encode oneKit error response", logger.Error(err))
	}
}
