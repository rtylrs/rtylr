package domain

import "time"

// Work-mode values. A day carries one as its default and a line may override it.
const (
	WorkModeOnsite = "onsite"
	WorkModeRemote = "remote"
	WorkModeHybrid = "hybrid"
)

// Work-day states. A day is approved once its date has passed; an approved day
// can be reopened, which returns it to the queue.
const (
	WorkDayStatusDraft     = "draft"
	WorkDayStatusSubmitted = "submitted"
	WorkDayStatusApproved  = "approved"
	WorkDayStatusRejected  = "rejected"
	WorkDayStatusReopened  = "reopened"
)

// ValidWorkMode reports whether a mode is one this product recognises. Modes
// arrive from a client, so an unrecognised one is rejected rather than stored.
func ValidWorkMode(mode string) bool {
	switch mode {
	case WorkModeOnsite, WorkModeRemote, WorkModeHybrid:
		return true
	default:
		return false
	}
}

// WorkDay is one person's working day.
type WorkDay struct {
	ID         int64
	EmployeeID int64
	// UserID is the employee's auth user id, set only where the caller
	// already resolved it (the team view, joining against workspace
	// membership) - zero for a caller reading their own day.
	UserID       int64
	Date         time.Time
	Timezone     string
	WorkMode     string
	StartTime    string
	EndTime      string
	BreakMinutes int32
	Status       string
	LoggedBy     int64
	ApprovedBy   int64
	ApprovedAt   time.Time
	ReopenedBy   int64
	ReopenedAt   time.Time
	CreatedAt    time.Time
	UpdatedAt    time.Time

	// ClockedMinutes is end minus start minus breaks, or zero when the day was
	// never clocked. LoggedMinutes is the sum of its lines. Gap is the first
	// minus the second: reported, never enforced, because blocking a submission
	// on it produces invented lines rather than honest ones.
	ClockedMinutes int32
	LoggedMinutes  int32
	GapMinutes     int32
}

