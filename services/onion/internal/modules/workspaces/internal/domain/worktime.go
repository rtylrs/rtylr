// ClockedMinutes derives the day's clocked total from its start, end and breaks.
// Returns zero when either end of the clock is missing, which is a legitimate
// day that recorded only its lines.
//
// An end before the start is treated as crossing midnight rather than as an
// error: a night shift that ends at 02:00 worked those hours.
func ClockedMinutes(startTime, endTime string, breakMinutes int32) int32 {
	start, okStart := parseClock(startTime)
	end, okEnd := parseClock(endTime)
	if !okStart || !okEnd {
		return 0
	}
	if end < start {
		end += 24 * 60
	}
	total := end - start - breakMinutes
	if total < 0 {
		return 0
	}
	return total
}

// parseClock reads a local HH:MM into minutes past midnight.
func parseClock(value string) (int32, bool) {
	if len(value) != 5 || value[2] != ':' {
		return 0, false
	}
	hours, ok := atoi2(value[0:2])
	if !ok || hours > 23 {
		return 0, false
	}
	minutes, ok := atoi2(value[3:5])
	if !ok || minutes > 59 {
		return 0, false
	}
	return int32(hours)*60 + int32(minutes), true // #nosec G115 -- Reviewed width conversion uses validated application limits and the established database or contract field width.
}

func atoi2(value string) (int, bool) {
	result := 0
	for i := 0; i < len(value); i++ {
		if value[i] < '0' || value[i] > '9' {
			return 0, false
		}
		result = result*10 + int(value[i]-'0')
	}
	return result, true
}
