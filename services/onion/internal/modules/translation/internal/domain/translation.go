package domain

import (
	"time"

	sqlc "github.com/voxire/onion/internal/modules/translation/internal/infrastructure/persistence/sqlc"
	"github.com/voxire/onion/internal/platform/utils/convert"
)

type Translation struct {
	ID            int
	KeyText       string
	En            string
	Ar            string
	Fr            string
	KeyGroup      string
	AutoGenerated bool
	CreatedAt     time.Time
	UpdatedAt     time.Time
}

type TranslationInput struct {
	KeyText       string
	En            string
	Ar            string
	Fr            string
	KeyGroup      string
	AutoGenerated bool
}

func (t *Translation) FromRow(row sqlc.GetTranslationRow) {
	t.KeyText = row.KeyText
	t.En = convert.ToString(row.En)
	t.Ar = convert.ToString(row.Ar)
	t.Fr = convert.ToString(row.Fr)
}
