-- Local schema for sqlc (production DDL from schemas/voxire + schemas/recruit migrations).
CREATE TABLE IF NOT EXISTS careers (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    business_id BIGINT NOT NULL DEFAULT 0,
    owner_id BIGINT NOT NULL DEFAULT 0,
    slug VARCHAR(120) NOT NULL DEFAULT '',
    title VARCHAR(255) NOT NULL,
    department VARCHAR(100) NULL,
    location VARCHAR(100) NULL,
    employment_type VARCHAR(50) NULL,
    work_mode VARCHAR(20) NULL,
    seniority VARCHAR(50) NULL,
    details TEXT NOT NULL,
    requirements TEXT NULL,
    salary_min DECIMAL(12,2) NULL,
    salary_max DECIMAL(12,2) NULL,
    salary_currency VARCHAR(8) NULL,
    is_published BOOLEAN NOT NULL DEFAULT false,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_careers_owner_slug (owner_id, slug),
    INDEX idx_careers_owner (owner_id)
);

CREATE TABLE IF NOT EXISTS careers_customizations (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    slug VARCHAR(80) NOT NULL,
    brand_name VARCHAR(120) NOT NULL,
    tagline VARCHAR(240) NULL,
    about_blurb TEXT NULL,
    logo_url VARCHAR(500) NULL,
    primary_color VARCHAR(16) NULL,
    accent_color VARCHAR(16) NULL,
    bg_color VARCHAR(16) NULL,
    text_color VARCHAR(16) NULL,
    muted_text_color VARCHAR(16) NULL,
    font_pairing VARCHAR(32) NULL,
    hero_image_url VARCHAR(500) NULL,
    favicon_url VARCHAR(500) NULL,
    template VARCHAR(32) NOT NULL DEFAULT 'minimal',
    header_html TEXT NULL,
    meta_title VARCHAR(240) NULL,
    meta_description VARCHAR(320) NULL,
    privacy_url VARCHAR(500) NULL,
    terms_url VARCHAR(500) NULL,
    ga_measurement_id VARCHAR(32) NULL,
    meta_pixel_id VARCHAR(32) NULL,
    require_consent BOOLEAN NOT NULL DEFAULT false,
    notification_email VARCHAR(160) NULL,
    email_notifications BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_careers_customizations_owner (owner_id),
    UNIQUE KEY uk_careers_customizations_slug (slug)
);

CREATE TABLE IF NOT EXISTS careers_submissions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    career_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    candidate_name VARCHAR(160) NOT NULL,
    email VARCHAR(160) NOT NULL,
    phone VARCHAR(40) NULL,
    resume_url VARCHAR(500) NULL,
    cover_letter TEXT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'new',
    answers_json JSON NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_careers_submissions_career (career_id),
    INDEX idx_careers_submissions_owner (owner_id),
    INDEX idx_careers_submissions_status (owner_id, status)
);

CREATE TABLE IF NOT EXISTS careers_sections (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    kind VARCHAR(32) NOT NULL,
    title VARCHAR(240) NULL,
    body TEXT NULL,
    media_url VARCHAR(500) NULL,
    items_json JSON NULL,
    position INT NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_careers_sections_owner (owner_id),
    INDEX idx_careers_sections_owner_pos (owner_id, position)
);

CREATE TABLE IF NOT EXISTS careers_form_fields (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    career_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL DEFAULT 0,
    kind VARCHAR(32) NOT NULL,
    label VARCHAR(240) NOT NULL,
    placeholder VARCHAR(240) NULL,
    required BOOLEAN NOT NULL DEFAULT false,
    options_json JSON NULL,
    position INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_careers_form_fields_career (career_id),
    INDEX idx_careers_form_fields_owner (owner_id)
);

CREATE TABLE IF NOT EXISTS voxire_career_applications (
    id                 BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    job_id             BIGINT NOT NULL,
    name               VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    phone              VARCHAR(100),
    work_history       TEXT,
    education          TEXT,
    experience_summary TEXT,
    cover_letter       TEXT,
    cv_key             VARCHAR(500),
    location           VARCHAR(160),
    salary_expectation DECIMAL(12,2),
    salary_currency    VARCHAR(8) DEFAULT 'USD',
    status             VARCHAR(32) NOT NULL DEFAULT 'new',
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_career_apps_job (job_id),
    INDEX idx_career_apps_status (status)
);
