// availabilityCaller resolves the tenant and the signed-in user, which every
// availability operation needs: the tenant to scope the query and the user to
// decide whether the operation is self-service.
func availabilityCaller(ctx context.Context) (businessID, userID int64, err error) {
	device := authPkg.DeviceCtx(ctx)
	if device.IsAnonymous || device.User == nil {
		return 0, 0, onekiterrors.PermissionDenied()
	}
	businessID, bizErr := tenant.ResolveBusinessID(ctx, device.User.BusinessID, device.User.UserID)
	if bizErr != nil {
		return 0, 0, onekiterrors.PermissionDenied()
	}
	return businessID, device.User.UserID, nil
}

// availabilityWriteError maps the domain errors a write can produce onto HTTP.
func availabilityWriteError(ctx context.Context, businessID int64, op string, err error) error {
	switch {
	case errors.Is(err, domain.ErrPermissionDenied):
		return onekiterrors.PermissionDenied()
	case errors.Is(err, domain.ErrAvailabilityNotFound):
		return onekiterrors.New(http.StatusNotFound, "Availability entry not found")
	case errors.Is(err, domain.ErrStaffNotLinked):
		return onekiterrors.New(http.StatusForbidden, "No staff record is linked to this account")
	case errors.Is(err, domain.ErrAvailabilityKindAmbiguous),
		errors.Is(err, domain.ErrAvailabilityDayOutOfRange),
		errors.Is(err, domain.ErrAvailabilityDateInvalid),
		errors.Is(err, domain.ErrAvailabilityTimeInvalid):
		return onekiterrors.New(http.StatusBadRequest, err.Error())
	}
	logger.Ctx(ctx).Error("availability operation failed",
		logger.Any("business_id", businessID), logger.String("operation", op), logger.Error(err))
	return onekiterrors.New(http.StatusInternalServerError, "Failed to "+op)
}

// ListAvailabilityRoutes includes the legacy route and the path generated by
// the hr.shift.v1 contract. Keeping both avoids breaking existing clients
// while making the contract route usable by the frontend.
func ListAvailabilityRoutes() []string {
	return []string{"/hr/shifts/availability", "/hr/shift/v1/availability"}
}

type ListAvailabilityHandler struct{ Service *application.Service }

type ListAvailabilityRequest struct {
	StaffID   int64  `json:"staff_id"`
	DayOfWeek *int32 `json:"day_of_week"`
	DateFrom  string `json:"date_from"`
	DateTo    string `json:"date_to"`
	Limit     int32  `json:"limit"`
	Offset    int32  `json:"offset"`
}

type ListAvailabilityResponse struct {
	Entries []*hrshiftv1.AvailabilityPayload `json:"entries"`
	Total   int64                            `json:"total"`
	Limit   int32                            `json:"limit"`
	Offset  int32                            `json:"offset"`
}

func (h *ListAvailabilityHandler) Serve(ctx context.Context, req *ListAvailabilityRequest) (ListAvailabilityResponse, error) {
	businessID, userID, err := availabilityCaller(ctx)
	if err != nil {
		return ListAvailabilityResponse{}, err
	}

	params := domain.ListAvailabilityParams{
		Limit:     req.Limit,
		Offset:    req.Offset,
		StaffID:   req.StaffID,
		DayOfWeek: req.DayOfWeek,
		DateFrom:  req.DateFrom,
		DateTo:    req.DateTo,
	}

	entries, total, err := h.Service.ListAvailability(ctx, businessID, userID, params)
	if err != nil {
		return ListAvailabilityResponse{}, availabilityWriteError(ctx, businessID, "list availability", err)
	}

	payloads := make([]*hrshiftv1.AvailabilityPayload, 0, len(entries))
	for _, e := range entries {
		payloads = append(payloads, availabilityToProto(e))
	}

	limit := params.Limit
	if limit <= 0 {
		limit = 20
	}
	if limit > 100 {
		limit = 100
	}

	return ListAvailabilityResponse{
		Entries: payloads,
		Total:   total,
		Limit:   limit,
		Offset:  params.Offset,
	}, nil
}

func SetAvailabilityRoutes() []string {
	return []string{"/hr/shifts/availability", "/hr/shift/v1/availability"}
}

type SetAvailabilityHandler struct{ Service *application.Service }

type SetAvailabilityRequest struct {
	ID           int64  `json:"id"`
	StaffID      int64  `json:"staff_id"`
	DayOfWeek    *int32 `json:"day_of_week"`
	SpecificDate string `json:"specific_date"`
	StartTime    string `json:"start_time"`
	EndTime      string `json:"end_time"`
	// IsAvailable is a pointer so an explicit false is distinguishable from the
	// field being omitted. Absent means true, the ordinary case of declaring
	// availability; without the distinction, omitting it would silently block
	// the window.
	IsAvailable *bool `json:"is_available"`
}

type SetAvailabilityResponse struct {
	Entry *hrshiftv1.AvailabilityPayload `json:"entry"`
}

func (h *SetAvailabilityHandler) Validate(_ context.Context, req *SetAvailabilityRequest) error {
	if req.StaffID <= 0 {
		return onekiterrors.New(http.StatusBadRequest, "staff_id is required")
	}
	if req.StartTime == "" {
		return onekiterrors.New(http.StatusBadRequest, "start_time is required")
	}
	if req.EndTime == "" {
		return onekiterrors.New(http.StatusBadRequest, "end_time is required")
	}
	// The contract requires exactly one of day_of_week and specific_date, which
	// `.onk` cannot express, so it is checked here as well as in the domain.
	if (req.DayOfWeek == nil) == (req.SpecificDate == "") {
		return onekiterrors.New(http.StatusBadRequest, "exactly one of day_of_week and specific_date must be set")
	}
	return nil
}

func (h *SetAvailabilityHandler) Serve(ctx context.Context, req *SetAvailabilityRequest) (SetAvailabilityResponse, error) {
	businessID, userID, err := availabilityCaller(ctx)
	if err != nil {
		return SetAvailabilityResponse{}, err
	}

	entry := domain.AvailabilityRecord{
		ID:           req.ID,
		StaffID:      req.StaffID,
		DayOfWeek:    domain.NoDayOfWeek,
		SpecificDate: req.SpecificDate,
		StartTime:    req.StartTime,
		EndTime:      req.EndTime,
		IsAvailable:  req.IsAvailable == nil || *req.IsAvailable,
	}
	if req.DayOfWeek != nil {
		entry.DayOfWeek = *req.DayOfWeek
	}

	saved, err := h.Service.SetAvailability(ctx, businessID, userID, entry)
	if err != nil {
		return SetAvailabilityResponse{}, availabilityWriteError(ctx, businessID, "save availability", err)
	}

	return SetAvailabilityResponse{Entry: availabilityToProto(*saved)}, nil
}

func DeleteAvailabilityRoutes() []string {
	return []string{"/hr/shifts/availability", "/hr/shift/v1/availability/{id}"}
}

type DeleteAvailabilityHandler struct{ Service *application.Service }

type DeleteAvailabilityRequest struct {
	ID int64 `json:"id"`
}

type DeleteAvailabilityResponse struct {
	Success bool `json:"success"`
}

func (h *DeleteAvailabilityHandler) Validate(_ context.Context, _ *DeleteAvailabilityRequest) error {
	return nil
}

func (h *DeleteAvailabilityHandler) Serve(ctx context.Context, req *DeleteAvailabilityRequest) (DeleteAvailabilityResponse, error) {
	if req.ID <= 0 {
		pathID := ""
		if routeContext := chi.RouteContext(ctx); routeContext != nil {
			pathID = routeContext.URLParam("id")
		}
		parsedID, parseErr := strconv.ParseInt(pathID, 10, 64)
		if parseErr != nil || parsedID <= 0 {
			return DeleteAvailabilityResponse{}, onekiterrors.New(http.StatusBadRequest, "id is required")
		}
		req.ID = parsedID
	}

	businessID, userID, err := availabilityCaller(ctx)
	if err != nil {
		return DeleteAvailabilityResponse{}, err
	}

	if err := h.Service.DeleteAvailability(ctx, businessID, userID, req.ID); err != nil {
		return DeleteAvailabilityResponse{}, availabilityWriteError(ctx, businessID, "delete availability", err)
	}

	return DeleteAvailabilityResponse{Success: true}, nil
}
