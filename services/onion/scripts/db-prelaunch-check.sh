#!/bin/bash
# Seed synthetic tenant volume and print EXPLAIN plans for the DB paths we care
# about before launch. This is intentionally staging/dev tooling: point DB_* at
# a migrated database, then run `make db-prelaunch-check`.

set -eo pipefail

DB_HOST="${DB_HOST:-localhost}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-onion_dev}"
DB_USER="${DB_USER:-onion_user}"
DB_PASSWORD="${DB_PASSWORD:-onion_password}"

BUSINESS_ID="${PRELAUNCH_BUSINESS_ID:-990001}"
OWNER_ID="${PRELAUNCH_OWNER_ID:-990001}"
LOCATION_ID="${PRELAUNCH_LOCATION_ID:-990001}"
STAFF_COUNT="${PRELAUNCH_STAFF_COUNT:-80}"
PRODUCT_COUNT="${PRELAUNCH_PRODUCT_COUNT:-2500}"
ORDER_COUNT="${PRELAUNCH_ORDER_COUNT:-5000}"
PRODUCT_ID_BASE="${PRELAUNCH_PRODUCT_ID_BASE:-9900010000}"
ORDER_ID_BASE="${PRELAUNCH_ORDER_ID_BASE:-9900020000}"

mysql_base=(
  mysql
  --host="$DB_HOST"
  --port="$DB_PORT"
  --user="$DB_USER"
  --database="$DB_NAME"
)

run_mysql() {
  MYSQL_PWD="$DB_PASSWORD" "${mysql_base[@]}" "$@"
}

info() {
  printf '[db-prelaunch] %s\n' "$1"
}

if ! command -v mysql >/dev/null 2>&1; then
  echo "mysql client is required" >&2
  exit 1
fi

info "target: $DB_USER@$DB_HOST:$DB_PORT/$DB_NAME"
info "synthetic tenant: business_id=$BUSINESS_ID owner_id=$OWNER_ID"
info "volume: staff=$STAFF_COUNT products=$PRODUCT_COUNT orders=$ORDER_COUNT"

run_mysql <<SQL
SET @business_id := ${BUSINESS_ID};
SET @owner_id := ${OWNER_ID};
SET @location_id := ${LOCATION_ID};
SET @staff_count := ${STAFF_COUNT};
SET @product_count := ${PRODUCT_COUNT};
SET @order_count := ${ORDER_COUNT};
SET @product_id_base := ${PRODUCT_ID_BASE};
SET @order_id_base := ${ORDER_ID_BASE};

INSERT INTO users (id, business_id, email, password_hash, full_name, onboarded)
VALUES (@owner_id, @business_id, CONCAT('prelaunch-owner-', @business_id, '@rtylr.local'), 'prelaunch', 'Prelaunch Owner', TRUE)
ON DUPLICATE KEY UPDATE
  business_id = VALUES(business_id),
  full_name = VALUES(full_name),
  onboarded = VALUES(onboarded);

INSERT INTO businesses (id, name, owner_id, industry, country, timezone, currency, slug, is_active)
VALUES (@business_id, CONCAT('Prelaunch Load ', @business_id), @owner_id, 'retail', 'US', 'UTC', 'USD', CONCAT('prelaunch-', @business_id), TRUE)
ON DUPLICATE KEY UPDATE
  owner_id = VALUES(owner_id),
  industry = VALUES(industry),
  is_active = VALUES(is_active);

INSERT INTO config (
  owner_id, business_id, site_name, logo_url, favicon_url, meta_tags,
  contact_email, contact_number, instagram, about_content, footer_sub_text,
  business_slug
)
SELECT
  @owner_id, @business_id, 'Prelaunch Store', '', '', JSON_ARRAY(),
  'prelaunch@rtylr.local', '+10000000000', '', 'Synthetic prelaunch load tenant',
  'Generated by db-prelaunch-check.sh', CONCAT('prelaunch-', @business_id)
WHERE NOT EXISTS (
  SELECT 1 FROM config WHERE business_id = @business_id LIMIT 1
);

UPDATE config
SET site_name = 'Prelaunch Store',
    contact_email = 'prelaunch@rtylr.local',
    contact_number = '+10000000000',
    business_slug = CONCAT('prelaunch-', @business_id)
WHERE business_id = @business_id;

INSERT INTO pos_locations (id, owner_id, business_id, name, is_active, timezone, currency)
VALUES (@location_id, @owner_id, @business_id, 'Prelaunch Main', TRUE, 'UTC', 'USD')
ON DUPLICATE KEY UPDATE
  business_id = VALUES(business_id),
  name = VALUES(name),
  is_active = VALUES(is_active);

DROP PROCEDURE IF EXISTS seed_rtylr_prelaunch;
DELIMITER //
CREATE PROCEDURE seed_rtylr_prelaunch()
BEGIN
  DECLARE i INT DEFAULT 1;
  DECLARE uid BIGINT;
  DECLARE pid BIGINT;
  DECLARE oid BIGINT;

  WHILE i <= @staff_count DO
    SET uid = @owner_id + i;

    INSERT INTO users (id, business_id, email, password_hash, full_name, onboarded)
    VALUES (uid, @business_id, CONCAT('prelaunch-staff-', @business_id, '-', i, '@rtylr.local'), 'prelaunch', CONCAT('Prelaunch Staff ', i), TRUE)
    ON DUPLICATE KEY UPDATE
      business_id = VALUES(business_id),
      full_name = VALUES(full_name),
      onboarded = VALUES(onboarded);

    INSERT INTO pos_member_locations (
      business_id, user_id, location_id,
      can_manage_pos_users, can_manage_terminals, can_view_reports
    )
    VALUES (@business_id, uid, @location_id, i <= 5, i <= 5, i <= 10)
    ON DUPLICATE KEY UPDATE
      can_manage_pos_users = VALUES(can_manage_pos_users),
      can_manage_terminals = VALUES(can_manage_terminals),
      can_view_reports = VALUES(can_view_reports);

    INSERT INTO pos_users (
      owner_id, business_id, user_id, location_id, name, pin_hash, role,
      is_active, hourly_rate, max_discount_pct, can_void, can_refund,
      can_open_drawer, can_apply_discount, created_by
    )
    VALUES (
      @owner_id, @business_id, uid, @location_id, CONCAT('Prelaunch Staff ', i),
      CONCAT('prelaunch-hash-', i),
      CASE WHEN i <= 5 THEN 'manager' ELSE 'cashier' END,
      TRUE, 15.00, CASE WHEN i <= 5 THEN 100 ELSE 10 END,
      i <= 5, i <= 5, i <= 10, i <= 10, @owner_id
    )
    ON DUPLICATE KEY UPDATE
      business_id = VALUES(business_id),
      name = VALUES(name),
      pin_hash = VALUES(pin_hash),
      role = VALUES(role),
      is_active = VALUES(is_active);

    SET i = i + 1;
  END WHILE;

  SET i = 1;
  WHILE i <= @product_count DO
    SET pid = @product_id_base + i;

    INSERT INTO erp_products (
      id, owner_id, business_id, name, sku, barcode, description, unit,
      cost_price, sale_price, stock_quantity, low_stock_threshold,
      reorder_quantity, is_active, track_inventory
    )
    VALUES (
      pid, @owner_id, @business_id,
      CONCAT('Prelaunch Product ', LPAD(i, 5, '0')),
      CONCAT('PRE-SKU-', @business_id, '-', LPAD(i, 5, '0')),
      CONCAT('PRE-BAR-', @business_id, '-', LPAD(i, 5, '0')),
      'Synthetic product for prelaunch DB checks',
      'unit',
      4 + MOD(i, 35),
      8 + MOD(i, 90),
      MOD(i, 180),
      8,
      12,
      TRUE,
      TRUE
    )
    ON DUPLICATE KEY UPDATE
      business_id = VALUES(business_id),
      name = VALUES(name),
      sku = VALUES(sku),
      barcode = VALUES(barcode),
      stock_quantity = VALUES(stock_quantity),
      sale_price = VALUES(sale_price);

    INSERT INTO erp_product_images (
      id, owner_id, business_id, product_id, url, alt, position, is_primary
    )
    VALUES (
      @product_id_base + 10000000 + i,
      @owner_id,
      @business_id,
      pid,
      CONCAT('https://cdn.rtylr.local/prelaunch/products/', i, '.jpg'),
      CONCAT('Prelaunch product ', i),
      0,
      TRUE
    )
    ON DUPLICATE KEY UPDATE
      business_id = VALUES(business_id),
      product_id = VALUES(product_id),
      url = VALUES(url),
      is_primary = VALUES(is_primary);

    SET i = i + 1;
  END WHILE;

  SET i = 1;
  WHILE i <= @order_count DO
    SET oid = @order_id_base + i;
    SET pid = @product_id_base + 1 + MOD(i, @product_count);

    INSERT INTO pos_orders (
      id, owner_id, business_id, session_id, table_id, location_id, order_number,
      type, status, customer_name, customer_phone, staff_id, subtotal, total,
      payment_method, payment_status, amount_paid, paid_at, created_at
    )
    VALUES (
      oid,
      @owner_id,
      @business_id,
      NULL,
      NULL,
      @location_id,
      CONCAT('PRE-', @business_id, '-', LPAD(i, 7, '0')),
      CASE WHEN MOD(i, 3) = 0 THEN 'takeaway' ELSE 'dine_in' END,
      CASE
        WHEN MOD(i, 11) = 0 THEN 'refunded'
        WHEN MOD(i, 5) = 0 THEN 'pending'
        ELSE 'paid'
      END,
      CONCAT('Customer ', MOD(i, 1000)),
      CONCAT('+1555', LPAD(MOD(i, 1000000), 6, '0')),
      @owner_id + 1 + MOD(i, @staff_count),
      10 + MOD(i, 250),
      10 + MOD(i, 250),
      CASE WHEN MOD(i, 4) = 0 THEN 'card' ELSE 'cash' END,
      CASE WHEN MOD(i, 5) = 0 THEN 'unpaid' ELSE 'paid' END,
      CASE WHEN MOD(i, 5) = 0 THEN 0 ELSE 10 + MOD(i, 250) END,
      CASE WHEN MOD(i, 5) = 0 THEN NULL ELSE DATE_SUB(NOW(), INTERVAL MOD(i, 45) DAY) END,
      DATE_SUB(NOW(), INTERVAL MOD(i, 45) DAY)
    )
    ON DUPLICATE KEY UPDATE
      business_id = VALUES(business_id),
      status = VALUES(status),
      payment_status = VALUES(payment_status),
      total = VALUES(total),
      paid_at = VALUES(paid_at),
      created_at = VALUES(created_at);

    INSERT INTO pos_order_items (
      id, order_id, menu_item_id, name, sku, quantity, unit_price, total, status
    )
    VALUES (
      @order_id_base + 10000000 + i,
      oid,
      pid,
      CONCAT('Prelaunch Product ', LPAD(1 + MOD(i, @product_count), 5, '0')),
      CONCAT('PRE-SKU-', @business_id, '-', LPAD(1 + MOD(i, @product_count), 5, '0')),
      1,
      10 + MOD(i, 250),
      10 + MOD(i, 250),
      'served'
    )
    ON DUPLICATE KEY UPDATE
      order_id = VALUES(order_id),
      menu_item_id = VALUES(menu_item_id),
      total = VALUES(total);

    SET i = i + 1;
  END WHILE;
END//
DELIMITER ;

CALL seed_rtylr_prelaunch();
DROP PROCEDURE IF EXISTS seed_rtylr_prelaunch;
SQL

info "synthetic data ready"

explain() {
  local label="$1"
  local query="$2"
  printf '\n[db-prelaunch] EXPLAIN %s\n' "$label"
  run_mysql --table -e "EXPLAIN ${query}"
}

explain "erp products page with primary image" "
SELECT p.id, p.name, p.sku, COALESCE(img.url, '') AS image_url
FROM erp_products p
LEFT JOIN erp_product_images img ON img.id = (
  SELECT i.id
  FROM erp_product_images i
  WHERE i.business_id = p.business_id
    AND i.product_id = p.id
  ORDER BY i.is_primary DESC, i.position ASC, i.id ASC
  LIMIT 1
)
WHERE p.business_id = ${BUSINESS_ID}
ORDER BY p.name ASC
LIMIT 50"

explain "erp product search" "
SELECT p.id, p.name, p.sku
FROM erp_products p
WHERE p.business_id = ${BUSINESS_ID}
  AND MATCH(p.name, p.sku, p.barcode) AGAINST ('prelaunch* product*' IN BOOLEAN MODE)
LIMIT 50"

explain "erp barcode lookup" "
SELECT id, name, sku, barcode
FROM erp_products
WHERE business_id = ${BUSINESS_ID}
  AND barcode = CONCAT('PRE-BAR-', ${BUSINESS_ID}, '-00001')
LIMIT 1"

explain "erp inventory report" "
SELECT id, name, sku, stock_quantity, low_stock_threshold
FROM erp_products
WHERE business_id = ${BUSINESS_ID}
  AND is_active = TRUE
  AND track_inventory = TRUE
ORDER BY name ASC
LIMIT 50"

explain "erp low stock report" "
SELECT id, name, sku, stock_quantity, low_stock_threshold
FROM erp_products
WHERE business_id = ${BUSINESS_ID}
  AND is_active = TRUE
  AND track_inventory = TRUE
  AND low_stock_threshold IS NOT NULL
  AND stock_quantity <= low_stock_threshold
ORDER BY stock_quantity ASC
LIMIT 50"

explain "pos location roster" "
SELECT ml.user_id, u.full_name, pu.id
FROM pos_member_locations ml
JOIN users u ON u.id = ml.user_id
LEFT JOIN pos_users pu
  ON pu.user_id = ml.user_id
 AND pu.location_id = ml.location_id
 AND pu.is_active = TRUE
WHERE ml.business_id = ${BUSINESS_ID}
  AND ml.location_id = ${LOCATION_ID}
ORDER BY u.full_name ASC"

explain "pos orders newest page" "
SELECT id, order_number, status, total, created_at
FROM pos_orders
WHERE business_id = ${BUSINESS_ID}
ORDER BY created_at DESC
LIMIT 51"

explain "pos orders paid today aggregate" "
SELECT COALESCE(SUM(total), 0), COUNT(*), COALESCE(AVG(total), 0)
FROM pos_orders
WHERE business_id = ${BUSINESS_ID}
  AND payment_status = 'paid'
  AND paid_at >= CURDATE()
  AND paid_at < DATE_ADD(CURDATE(), INTERVAL 1 DAY)"

explain "config lookup" "
SELECT owner_id, business_id, site_name
FROM config
WHERE business_id = ${BUSINESS_ID}"

explain "feature gate owner targets" "
SELECT id, feature_key, owner_id, enabled, variant
FROM feature_targets
WHERE owner_id = ${OWNER_ID}"

info "done"
