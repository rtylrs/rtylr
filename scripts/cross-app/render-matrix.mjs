#!/usr/bin/env node
// Renders the 12x12 domain sharing matrix from docs/cross-app/connections.json
// into docs/cross-app/generated-matrix.md, which 03-sharing-matrix.md embeds.
//
// The point of generating it is completeness: every one of the 132 ordered
// pairs gets a cell, and any pair with no connection gets an explicit reason
// code rather than a blank. A blank cell in the output means the reason rules
// below did not cover that pair, which is a bug in this script, and it is
// reported as UNEXPLAINED on stderr with a non-zero exit.
//
//   node scripts/cross-app/render-matrix.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('../..', import.meta.url).pathname.replace(/\/$/, '');
const IN = join(ROOT, 'docs/cross-app/connections.json');
const OUT = join(ROOT, 'docs/cross-app/generated-matrix.md');

const data = JSON.parse(readFileSync(IN, 'utf8'));
const DOMAINS = data.domains;

// Domains with no operator surface in apps/. booking and support have
// contracts and onion modules but no app; pos serves the separate terminal
// repo; console is RTYLR's own cross-tenant admin.
const NO_SURFACE = new Set(['booking', 'support', 'pos']);
const INFRA = new Set(['common']);
const ADMIN = new Set(['console']);
// insights is a read-only projection layer: it consumes, nothing consumes it.
const TERMINAL = new Set(['insights']);

// Connections keyed by producer->consumer. Product-wide connections
// (consumer "all") are listed above the matrix instead of being fanned into
// every cell, which would make the producer's row unreadable and imply 12
// separate edges where there is one.
const byPair = new Map();
const productWide = [];
const intraDomain = [];
// A connection whose producer or consumer is not one of the 12 contract
// domains cannot occupy a matrix cell. The only such case is the recruit app,
// which has no contract domain at all (see 01-inventory.md); it is rendered in
// its own section rather than dropped, and the assertion at the end of this
// script fails if any connection goes unrendered.
const offMatrix = [];
for (const c of data.connections) {
  if (c.consumer === 'all') {
    productWide.push(c);
    continue;
  }
  if (c.producer === c.consumer) {
    intraDomain.push(c);
    continue;
  }
  if (!DOMAINS.includes(c.producer) || !DOMAINS.includes(c.consumer)) {
    offMatrix.push(c);
    continue;
  }
  const key = `${c.producer}>${c.consumer}`;
  if (!byPair.has(key)) byPair.set(key, []);
  byPair.get(key).push(c);
}

function reasonFor(p, q) {
  if (p === q) return 'self';
  if (INFRA.has(p) || INFRA.has(q)) return 'infra';
  if (p === 'hub') return 'hub-already-shared';
  if (ADMIN.has(p) || ADMIN.has(q)) return 'console';
  if (TERMINAL.has(p)) return 'insights-is-terminal';
  if (NO_SURFACE.has(q)) return 'no-consumer-surface';
  // A reverse edge that is proposed means this direction would invert it.
  if (byPair.has(`${q}>${p}`)) return 'would-invert';
  return 'no-producer-data';
}

const shortStatus = { proposed: '', rejected: ' (rejected)', existing: ' (existing)' };

const rows = [];
const header = ['producer \\ consumer', ...DOMAINS];
rows.push(header);
rows.push(header.map(() => '---'));

const unexplained = [];
const cellDetail = [];

for (const p of DOMAINS) {
  const row = [`**${p}**`];
  for (const q of DOMAINS) {
    const conns = byPair.get(`${p}>${q}`);
    if (conns?.length) {
      row.push(conns.map((c) => `${c.id}${shortStatus[c.status] ?? ''}`).join('<br/>'));
      for (const c of conns) cellDetail.push({ p, q, c });
    } else {
      const r = reasonFor(p, q);
      if (!r) unexplained.push(`${p}->${q}`);
      row.push(p === q ? '-' : `_${r}_`);
    }
  }
  rows.push(row);
}

const lines = [];
lines.push('<!-- GENERATED by scripts/cross-app/render-matrix.mjs. Do not edit by hand. -->');
lines.push('');
lines.push(
  `Rendered from \`connections.json\`: ${DOMAINS.length}x${DOMAINS.length} = ${DOMAINS.length * DOMAINS.length} ordered pairs, every one accounted for.`
);
lines.push('');
for (const r of rows) lines.push(`| ${r.join(' | ')} |`);
lines.push('');
if (productWide.length) {
  lines.push('### Product-wide connections (every domain is a consumer)');
  lines.push('');
  lines.push('| Id | Flows | Class | Status |');
  lines.push('| --- | --- | --- | --- |');
  for (const c of productWide) lines.push(`| ${c.id} | ${c.flows} | ${c.class} | ${c.status} |`);
  lines.push('');
}
if (intraDomain.length) {
  lines.push('### Intra-domain findings (not crossings, but blocking ones)');
  lines.push('');
  lines.push('| Id | Domain | Flows | Class | Status |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const c of intraDomain)
    lines.push(`| ${c.id} | ${c.producer} | ${c.flows} | ${c.class} | ${c.status} |`);
  lines.push('');
}
if (offMatrix.length) {
  lines.push('### Connections outside the domain matrix');
  lines.push('');
  lines.push(
    'These involve an app with no contract domain, so they have no cell. See `01-inventory.md` on the app-to-domain mismatch.'
  );
  lines.push('');
  lines.push('| Id | Producer | Consumer | Flows | Class | Status |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const c of offMatrix)
    lines.push(
      `| ${c.id} | ${c.producer} | ${c.consumer} | ${c.flows} | ${c.class} | ${c.status} |`
    );
  lines.push('');
}
lines.push('### Reason codes for pairs with no connection');
lines.push('');
lines.push('| Code | Meaning |');
lines.push('| --- | --- |');
for (const [k, v] of Object.entries(data.emptyCellReasons)) {
  lines.push(`| \`${k}\` | ${v} |`);
}

// Counts
const counts = { self: 0 };
for (const p of DOMAINS)
  for (const q of DOMAINS) {
    if (byPair.get(`${p}>${q}`)?.length) continue;
    const r = p === q ? 'self' : reasonFor(p, q);
    counts[r] = (counts[r] ?? 0) + 1;
  }
lines.push('');
lines.push('### Cell census');
lines.push('');
lines.push('| Outcome | Cells |');
lines.push('| --- | --- |');
const populated = DOMAINS.flatMap((p) =>
  DOMAINS.map((q) => byPair.get(`${p}>${q}`)?.length ?? 0)
).filter(Boolean).length;
lines.push(`| carries at least one connection id | ${populated} |`);
for (const [k, v] of Object.entries(counts).sort((a, b) => b[1] - a[1]))
  lines.push(`| \`${k}\` | ${v} |`);
const total = populated + Object.values(counts).reduce((a, b) => a + b, 0);
lines.push(`| **total cells** | **${total}** |`);
lines.push(`| of which self-pairs (not crossings) | ${counts.self ?? 0} |`);
lines.push(`| **ordered cross-domain pairs with a verdict** | **${total - (counts.self ?? 0)}** |`);

writeFileSync(OUT, lines.join('\n') + '\n');

// Inject the same content into 03-sharing-matrix.md between its markers, so
// the document is self-contained and re-running this script is idempotent.
const DOC = join(ROOT, 'docs/cross-app/03-sharing-matrix.md');
const BEGIN = '<!-- BEGIN GENERATED MATRIX -->';
const END = '<!-- END GENERATED MATRIX -->';
try {
  const doc = readFileSync(DOC, 'utf8');
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a === -1 || b === -1 || b < a) {
    process.stderr.write(`markers missing or malformed in ${relative(ROOT, DOC)}\n`);
    process.exit(1);
  }
  writeFileSync(
    DOC,
    doc.slice(0, a + BEGIN.length) + '\n\n' + lines.slice(2).join('\n') + '\n\n' + doc.slice(b)
  );
} catch (e) {
  process.stderr.write(`could not inject into the document: ${e.message}\n`);
  process.exit(1);
}

process.stdout.write(`${relative(ROOT, OUT)}: ${populated} populated cells, ${total} total\n`);
if (unexplained.length) {
  process.stderr.write(`UNEXPLAINED cells: ${unexplained.join(', ')}\n`);
  process.exit(1);
}
if (total !== DOMAINS.length * DOMAINS.length) {
  process.stderr.write(`cell count mismatch: ${total}\n`);
  process.exit(1);
}
// Every connection must be rendered somewhere, or the matrix silently hides it.
const rendered = new Set([
  ...cellDetail.map((d) => d.c.id),
  ...productWide.map((c) => c.id),
  ...intraDomain.map((c) => c.id),
  ...offMatrix.map((c) => c.id),
]);
const missing = data.connections.filter((c) => !rendered.has(c.id)).map((c) => c.id);
if (missing.length) {
  process.stderr.write(`connections not rendered anywhere: ${missing.join(', ')}\n`);
  process.exit(1);
}
process.stdout.write(`all ${data.connections.length} connections rendered\n`);
