#!/usr/bin/env node
// Renders docs/cross-app/05-connections/README.md (the dossier index) and
// docs/cross-app/11-rejected.md from connections.json, and asserts that every
// proposed connection has a dossier file and every dossier file corresponds to
// a proposed connection. Exits non-zero on any mismatch, so the index cannot
// drift from the data or from the filesystem.
//
//   node scripts/cross-app/render-connection-index.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('../..', import.meta.url).pathname.replace(/\/$/, '');
const DATA = join(ROOT, 'docs/cross-app/connections.json');
const DIR = join(ROOT, 'docs/cross-app/05-connections');

const data = JSON.parse(readFileSync(DATA, 'utf8'));
const files = readdirSync(DIR).filter((f) => f.endsWith('.md') && f !== 'README.md');

// Id "ERP->FIN-01" becomes filename prefix "ERP-FIN-01".
const prefixOf = (id) => id.replace(/->/g, '-').replace(/[^A-Za-z0-9-]/g, '');

const proposed = data.connections.filter((c) => c.status === 'proposed');
const rejected = data.connections.filter((c) => c.status === 'rejected');
const existing = data.connections.filter((c) => c.status === 'existing');

const problems = [];
const fileFor = new Map();
for (const c of proposed) {
  const hits = files.filter((f) => f.startsWith(prefixOf(c.id) + '-'));
  if (hits.length === 0) problems.push(`no dossier for ${c.id}`);
  else if (hits.length > 1) problems.push(`${c.id} matches several files: ${hits.join(', ')}`);
  else fileFor.set(c.id, hits[0]);
}
const claimed = new Set(fileFor.values());
for (const f of files) if (!claimed.has(f)) problems.push(`orphan dossier file: ${f}`);

const NEC_ORDER = { Essential: 0, 'High value': 1, 'Nice to have': 2 };
const SEV_ORDER = { critical: 0, high: 1, medium: 2, low: 3 };
const sorted = [...proposed].sort(
  (a, b) =>
    (NEC_ORDER[a.necessity] ?? 9) - (NEC_ORDER[b.necessity] ?? 9) ||
    (SEV_ORDER[a.severity] ?? 9) - (SEV_ORDER[b.severity] ?? 9) ||
    a.id.localeCompare(b.id)
);

const GAP_LABEL = {
  'available-today': 'Available today',
  'needs-endpoint': 'Needs a query or endpoint',
  'needs-contract-field': 'Needs a contract field',
  'needs-new-concept': 'Needs a new concept',
};

// --- index ------------------------------------------------------------------
const idx = [];
idx.push(
  '<!-- GENERATED by scripts/cross-app/render-connection-index.mjs. Do not edit by hand. -->'
);
idx.push('');
idx.push('# Connection dossiers');
idx.push('');
idx.push(
  `${proposed.length} proposals survived the bar in section 7 of the brief. ${rejected.length} candidates did not and are in [11-rejected.md](../11-rejected.md) with the rule each failed. ${existing.length} crossing already works and is documented as precedent.`
);
idx.push('');
idx.push(
  'Every dossier uses the same template: benefit, why this pairing, ROI with visible assumptions, the data with citations, what exists, what is missing, precedent, how to build it, coupling cost, risks, effort.'
);
idx.push('');
idx.push('| Id | What flows | Producer | Consumer | Class | Necessity | Severity | Gap | Shape |');
idx.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const c of sorted) {
  const link = `[${c.id}](${fileFor.get(c.id) ?? '#'})`;
  idx.push(
    `| ${link} | ${c.flows} | ${c.producer} | ${c.consumer} | ${c.class} | ${c.necessity} | ${c.severity ?? ''} | ${GAP_LABEL[c.gap] ?? c.gap} | ${c.shape} |`
  );
}
idx.push('');
idx.push('## By gap bucket');
idx.push('');
for (const [k, label] of Object.entries(GAP_LABEL)) {
  const items = sorted.filter((c) => c.gap === k);
  idx.push(`**${label}** (${items.length}): ${items.map((c) => c.id).join(', ') || 'none'}`);
  idx.push('');
}
idx.push('## By plumbing shape');
idx.push('');
idx.push('Shapes are ordered loosest first; rule 1 requires taking the first that works.');
idx.push('');
idx.push('| Shape | Name | Proposals |');
idx.push('| --- | --- | --- |');
for (const [n, name] of Object.entries(data.shapes)) {
  const items = sorted.filter((c) => String(c.shape) === n);
  idx.push(`| ${n} | ${name} | ${items.map((c) => c.id).join(', ') || 'none'} |`);
}
idx.push('');
idx.push('## By taxonomy reason');
idx.push('');
idx.push('| # | Reason | Proposals |');
idx.push('| --- | --- | --- |');
for (const [n, name] of Object.entries(data.taxonomy)) {
  const items = sorted.filter((c) => (c.why ?? []).map(String).includes(n));
  idx.push(`| ${n} | ${name} | ${items.map((c) => c.id).join(', ') || 'none'} |`);
}
writeFileSync(join(DIR, 'README.md'), idx.join('\n') + '\n');

// --- rejected ---------------------------------------------------------------
const RULE_LABEL = {
  'bar-1': 'Bar 1: must be Essential or High value',
  'bar-2': 'Bar 2: the loosest sufficient shape, or a stated reason why not',
  'bar-3': 'Bar 3: must survive the producing app being switched off',
  'bar-4': 'Bar 4: must have a positive modelled ROI',
  'bar-5': 'Bar 5: a customer would notice within a week',
};
const byRule = {};
for (const c of rejected) (byRule[c.failedRule] ??= []).push(c);

const rej = [];
rej.push(
  '<!-- GENERATED by scripts/cross-app/render-connection-index.mjs. Do not edit by hand. -->'
);
rej.push('');
rej.push('# 11. Rejected candidates');
rej.push('');
rej.push(
  `${rejected.length} of ${data.connections.length} candidates were rejected. Rejections are a deliverable: they are what stops the next engineer re-proposing the same bad edge. Each names the bar rule it failed.`
);
rej.push('');
rej.push(
  'The bar, from section 7 of the brief. A candidate becomes a proposal only if it clears all five:'
);
rej.push('');
for (const [k, v] of Object.entries(RULE_LABEL)) rej.push(`- \`${k}\` ${v}`);
rej.push('');
rej.push('## Rejections by rule');
rej.push('');
rej.push('| Rule | Count |');
rej.push('| --- | --- |');
for (const [k, v] of Object.entries(byRule).sort((a, b) => b[1].length - a[1].length))
  rej.push(`| \`${k}\` ${RULE_LABEL[k] ?? ''} | ${v.length} |`);
rej.push('');
for (const [k, items] of Object.entries(byRule).sort()) {
  rej.push(`## ${RULE_LABEL[k] ?? k}`);
  rej.push('');
  for (const c of items) {
    rej.push(`### ${c.id}: ${c.flows}`);
    rej.push('');
    rej.push(
      `- **Producer:** ${c.producer} → **Consumer:** ${c.consumer}. Class ${c.class}, necessity ${c.necessity}.`
    );
    rej.push(`- **Would have needed:** ${GAP_LABEL[c.gap] ?? c.gap}, shape ${c.shape}.`);
    rej.push('');
    rej.push(c.reason);
    rej.push('');
  }
}
// The most valuable rejections: cheap, obvious, and somebody will otherwise
// build them. Called out separately because a reader skimming by rule will
// miss the point that these were considered and declined on purpose.
const tempting = rejected.filter((c) => c.temptingBadIdea);
if (tempting.length) {
  rej.push('## Technically obvious, deliberately not worth it');
  rej.push('');
  rej.push(
    'These are the rejections that matter most, because each is cheap to build, looks like an improvement, and would leave a permanent dependency behind for very little return. If a future proposal re-raises one of these, the burden is to say what changed.'
  );
  rej.push('');
  rej.push('| Id | The tempting idea | Why not |');
  rej.push('| --- | --- | --- |');
  for (const c of tempting) rej.push(`| ${c.id} | ${c.flows} | ${c.reason} |`);
  rej.push('');
}

writeFileSync(join(ROOT, 'docs/cross-app/11-rejected.md'), rej.join('\n') + '\n');

process.stdout.write(
  `${proposed.length} dossiers indexed, ${rejected.length} rejections rendered\n`
);
if (problems.length) {
  for (const p of problems) process.stderr.write(`  ${p}\n`);
  process.exit(1);
}
