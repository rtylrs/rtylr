import React from 'react';
import { Printer } from 'lucide-react';
import type { PurchaseOrder } from '../../features/purchasing/usePurchaseOrders';
import { toast } from 'sonner';

interface PrintPOButtonProps {
  order: PurchaseOrder;
  supplierName: string;
}

const PrintPOButton: React.FC<PrintPOButtonProps> = ({ order, supplierName }) => {
  const itemCount = (order.items ?? []).length;
  const handlePrint = () => {
    const win = window.open('', '_blank', 'width=720,height=960');
    if (!win) {
      toast.error('Please allow popups to print');
      return;
    }
    const html = `<!doctype html>
<html>
  <head>
    <title>Purchase Order PO-${order.id}</title>
    <style>
      * { box-sizing: border-box; }
      body { font-family: Helvetica, Arial, sans-serif; padding: 32px; color: #111; }
      h1 { margin: 0 0 8px; font-size: 24px; }
      .muted { color: #666; font-size: 12px; }
      .row { display: flex; justify-content: space-between; margin: 20px 0; }
      .box { border: 1px solid #ddd; padding: 16px; border-radius: 8px; flex: 1; }
      .box + .box { margin-left: 16px; }
      .label { font-size: 10px; text-transform: uppercase; color: #888; letter-spacing: 0.05em; }
      .value { font-size: 14px; margin-top: 4px; font-weight: 600; }
      table { width: 100%; border-collapse: collapse; margin-top: 24px; }
      th, td { border: 1px solid #ddd; padding: 8px 12px; text-align: left; font-size: 12px; }
      th { background: #f5f5f5; text-transform: uppercase; font-size: 10px; letter-spacing: 0.05em; }
      .total { text-align: right; font-size: 16px; font-weight: 700; margin-top: 16px; }
      .footer { margin-top: 40px; font-size: 10px; color: #888; text-align: center; }
    </style>
  </head>
  <body>
    <h1>Purchase Order PO-${order.id}</h1>
    <p class="muted">rtylr Operations</p>
    <div class="row">
      <div class="box">
        <div class="label">Supplier</div>
        <div class="value">${supplierName}</div>
      </div>
      <div class="box">
        <div class="label">Order Date</div>
        <div class="value">${order.createdAt}</div>
      </div>
      <div class="box">
        <div class="label">Expected</div>
        <div class="value">${order.expectedDelivery ?? ''}</div>
      </div>
    </div>
    <table>
      <thead>
        <tr>
          <th>#</th>
          <th>Description</th>
          <th>Qty</th>
        </tr>
      </thead>
      <tbody>
        <tr><td>1</td><td>${itemCount} item${itemCount !== 1 ? 's' : ''} - see order details</td><td>${itemCount}</td></tr>
      </tbody>
    </table>
    <p class="total">Total: $${(order.total ?? 0).toFixed(2)}</p>
    <p class="footer">Generated by rtylr Operations - ${new Date().toLocaleString()}</p>
    <script>window.onload = () => window.print();</script>
  </body>
</html>`;
    win.document.write(html);
    win.document.close();
  };

  return (
    <button
      type="button"
      onClick={handlePrint}
      className="flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-medium"
      style={{
        background: 'var(--hub-hover)',
        color: 'var(--hub-text-muted)',
        border: '1px solid var(--hub-border)',
      }}
    >
      <Printer size={11} /> Print
    </button>
  );
};

export default PrintPOButton;
